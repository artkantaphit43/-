def header(ws, row, cols):
    for i, t in enumerate(cols):
        c = ws.cell(row=row, column=2 + i, value=t)
        c.font = Font(name=F, bold=True, color="FFFFFF")
        c.fill = HEAD_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BOX


def section(ws, row, text, ncols):
    c = ws.cell(row=row, column=2, value=text)
    c.font = Font(name=F, bold=True, size=12, color="1F4E78")
    for i in range(ncols):
        ws.cell(row=row, column=2 + i).fill = SUB_FILL


def put(ws, row, values, fmts=None, inputs=(), results=()):
    for i, v in enumerate(values):
        col = 2 + i
        c = ws.cell(row=row, column=col, value=v)
        c.font = Font(name=F, color="0000FF" if col in inputs else "000000", bold=col in results)
        c.border = BOX
        c.alignment = Alignment(vertical="center", wrap_text=True)
        if col in inputs:
            c.fill = IN_FILL
        elif col in results:
            c.fill = RES_FILL
        if fmts and fmts[i]:
            c.number_format = fmts[i]
            c.alignment = Alignment(horizontal="center", vertical="center")


def widths(ws, w):
    for col, width in w.items():
        ws.column_dimensions[col].width = width
    ws.column_dimensions["A"].width = 2


def note_lines(ws, row, lines):
    for j, t in enumerate(lines):
        ws.cell(row=row + j, column=2, value=t).font = Font(name=F)


