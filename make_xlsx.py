class Refs(dict):
    def __missing__(self, k):
        raise KeyError(f"ยังไม่มีค่า {k}")


def ceil(expr):
    return f"CEILING(ROUND({expr},4),{R['step']})"


def row(key, label, how, req, use, unit, why, fmt="0.000"):
    """req/use: สูตร Excel ที่ใช้ {ชื่อ} อ้างค่าอื่น; use='ceil' = ปัดค่าขั้นต่ำขึ้น, 'round' = ปัดใกล้สุด"""
    global r
    ref = Refs(R)
    req_f = ("=" + req.format_map(ref)) if req else ""
    if use == "ceil":
        use_f = "=" + ceil(f"D{r}")
    elif use == "round":
        use_f = f"=ROUND(D{r}/{R['step']},0)*{R['step']}"
    else:
        use_f = "=" + use.format_map(ref)
    put(ws, r, [label, how, req_f, use_f, unit, why], [None, None, fmt, fmt, None, None], results=(5,))
    if key:
        R[key] = f"{SH}!$E${r}"
    r += 1


def check(label, how, value, cond, why):
    global r
    ref = Refs(R)
    put(ws, r, [label, how, "=" + value.format_map(ref), f'=IF({cond.format_map(Refs({**R, "v": f"D{r}"}))},"ผ่าน ✔","ไม่ผ่าน ✘")', "", why],
        [None, None, "0.000", None, None, None], results=(5,))
    r += 1


def sec(text):
    global r
    r += 1
    section(ws, r, text, 6)
    r += 1


